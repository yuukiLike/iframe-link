/**
 * Playwright E2E 测试配置文件
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * 🎯 什么是 E2E 测试？
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * E2E (End-to-End) 测试模拟真实用户操作，在真实浏览器中测试完整功能流程。
 * 与单元测试不同，E2E 测试会：
 *   - 启动真实的浏览器（Chrome、Firefox 等）
 *   - 加载真实的 HTML 页面
 *   - 模拟用户点击、输入等操作
 *   - 验证页面上显示的结果
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * 🔄 测试执行流程
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 *   pnpm run test:e2e
 *         │
 *         ▼
 *   ┌─────────────────┐
 *   │  pnpm run build  │  ← 第一步：用 tsup 打包 SDK 到 dist/
 *   └────────┬────────┘
 *            ▼
 *   ┌─────────────────────────────────────────────────────────────┐
 *   │  Playwright 启动                                            │
 *   │                                                             │
 *   │  1. 根据 webServer 配置启动静态服务器 (serve)               │
 *   │     → pnpm exec serve . -l 3456 --cors                           │
 *   │     → 这样就能通过 http://localhost:3456 访问项目文件       │
 *   │                                                             │
 *   │  2. 启动浏览器（默认 Chromium，无头模式）                   │
 *   │                                                             │
 *   │  3. 执行 tests/e2e/ 目录下的测试文件                        │
 *   │     → 每个 test() 都会打开新页面执行                        │
 *   └─────────────────────────────────────────────────────────────┘
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * 📁 测试文件结构
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 *   tests/e2e/
 *   ├── fixtures/                    ← 测试用的 HTML 页面（模拟真实使用场景）
 *   │   ├── parent.html             ← 父页面，加载 SDK 并创建 iframe
 *   │   ├── child-sdk.html          ← 子页面，使用 SDK 与父页面通信
 *   │   └── child-traditional.html  ← 子页面，使用原生 postMessage
 *   │
 *   └── sdk-communication.spec.ts   ← 测试用例文件（.spec.ts 是约定命名）
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * 🛠️ 常用命令
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 *   pnpm run test:e2e          # 运行所有 E2E 测试（无头模式，看不到浏览器）
 *   pnpm run test:e2e:ui       # 打开可视化界面，可以看到测试执行过程（推荐新手使用！）
 *
 *   # 更多调试命令：
 *   pnpm exec playwright test --config config/playwright.config.ts --headed              # 显示浏览器窗口
 *   pnpm exec playwright test --config config/playwright.config.ts --debug               # 打开调试器，逐步执行
 *   pnpm exec playwright test --config config/playwright.config.ts --grep "handshake"    # 只运行名称包含 "handshake" 的测试
 *   pnpm exec playwright show-report docs/reports/playwright # 查看测试报告
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * ❓ 为什么用 serve 而不是 Vite？
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 *   E2E 测试的目的是测试「用户真正使用的产物」，也就是打包后的 dist/index.js
 *   而不是开发时经过 Vite 转换的代码。
 *
 *   serve 是一个简单的静态文件服务器，它：
 *   - 不做任何代码转换，直接返回文件
 *   - 启动快，没有编译开销
 *   - 更接近生产环境
 *
 */

import { defineConfig, devices } from '@playwright/test'

export default defineConfig({
  // ═══════════════════════════════════════════════════════════════════════════
  // 基础配置
  // ═══════════════════════════════════════════════════════════════════════════

  // 测试文件所在目录
  // Playwright 会自动查找这个目录下的 *.spec.ts 文件
  testDir: '../tests/e2e',

  // 是否并行执行测试
  // true = 多个测试文件同时运行，加快速度
  fullyParallel: true,

  // ═══════════════════════════════════════════════════════════════════════════
  // CI 环境特殊配置
  // ═══════════════════════════════════════════════════════════════════════════

  // 禁止使用 test.only()
  // 在 CI 环境中，如果有人不小心提交了 test.only()，会导致只运行部分测试
  // 这个配置会让 CI 直接报错，避免漏测
  forbidOnly: !!process.env.CI,

  // 失败重试次数
  // CI 环境重试 2 次（网络等原因可能导致偶发失败）
  // 本地不重试，方便快速发现问题
  retries: process.env.CI ? 2 : 0,

  // 并行工作进程数
  // CI 环境用 1 个（资源有限，避免不稳定）
  // 本地用 undefined（自动根据 CPU 核心数决定）
  workers: process.env.CI ? 1 : undefined,

  // ═══════════════════════════════════════════════════════════════════════════
  // 测试报告
  // ═══════════════════════════════════════════════════════════════════════════

  // 生成 HTML 格式的测试报告
  // 测试完成后运行 `pnpm exec playwright show-report docs/reports/playwright` 查看
  reporter: [['html', { outputFolder: '../docs/reports/playwright' }]],

  // 测试结果目录（存放失败时的截图、视频等）
  outputDir: '../docs/reports/test-results',

  // ═══════════════════════════════════════════════════════════════════════════
  // 全局测试配置（所有测试共享）
  // ═══════════════════════════════════════════════════════════════════════════

  use: {
    // 基础 URL，测试中可以用相对路径
    // 例如：page.goto('/tests/e2e/fixtures/parent.html')
    // 实际访问：http://localhost:3456/tests/e2e/fixtures/parent.html
    baseURL: 'http://localhost:3456',

    // 录制追踪信息（用于调试失败的测试）
    // 'on-first-retry' = 只在第一次重试时录制，节省资源
    // 录制内容包括：截图、DOM 快照、网络请求等
    trace: 'on-first-retry',
  },

  // ═══════════════════════════════════════════════════════════════════════════
  // 浏览器配置
  // ═══════════════════════════════════════════════════════════════════════════

  projects: [
    {
      name: 'chromium',
      // devices['Desktop Chrome'] 包含了 Chrome 浏览器的默认配置
      // 如视口大小、User-Agent 等
      use: { ...devices['Desktop Chrome'] },
    },
    // 可以添加更多浏览器：
    // { name: 'firefox', use: { ...devices['Desktop Firefox'] } },
    // { name: 'webkit', use: { ...devices['Desktop Safari'] } },
  ],

  // ═══════════════════════════════════════════════════════════════════════════
  // 测试服务器配置（重要！）
  // ═══════════════════════════════════════════════════════════════════════════

  webServer: {
    // 启动静态文件服务器的命令
    // serve: 一个简单的静态文件服务器（npm 包）
    // -l 3456: 监听 3456 端口
    // --cors: 允许跨域请求（iframe 通信需要）
    command: 'pnpm exec serve . -l 3456 --cors',
    cwd: '..',

    // Playwright 会等待这个 URL 可访问后才开始测试
    url: 'http://localhost:3456',

    // 是否复用已存在的服务器
    // 本地开发时如果已经手动启动了服务器，就复用它
    // CI 环境总是启动新的服务器
    reuseExistingServer: !process.env.CI,
  },
})
